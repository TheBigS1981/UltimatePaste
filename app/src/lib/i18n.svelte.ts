import pt from "./locales/pt.json";
import vi from "./locales/vi.json";

export type Lang = "de" | "en" | "it" | "es" | "fr" | "nl" | "pl" | "pt" | "vi";

/** UI languages with their own names. */
export const LANGS: { code: Lang; name: string }[] = [
  { code: "de", name: "Deutsch" },
  { code: "en", name: "English" },
  { code: "es", name: "Español" },
  { code: "fr", name: "Français" },
  { code: "it", name: "Italiano" },
  { code: "nl", name: "Nederlands" },
  { code: "pl", name: "Polski" },
  { code: "pt", name: "Português (Brasil)" },
  { code: "vi", name: "Tiếng Việt" },
];

/**
 * Translations for the other languages. Keys are the German text of a `tr(de, en)` call,
 * or "@<key>" for the keyed texts above. Missing entries fall back to English.
 */
const CATALOG: Record<string, Record<string, string>> = { it, es, fr, nl, pl, pt, vi };

export const i18n = $state({ lang: "de" as Lang });

const fill = (s: string, args: unknown[]) => args.reduce<string>((acc, a, i) => acc.replaceAll(`{${i}}`, String(a)), s);

/** Text in the UI language: German and English inline, the rest from the catalog. */
export function tr(de: string, en: string, ...args: unknown[]): string {
  const l = i18n.lang;
  const s = l === "de" ? de : l === "en" ? en : (CATALOG[l]?.[de] ?? en);
  return args.length ? fill(s, args) : s;
}

/** German for "de", otherwise English – for data that only exists in these two languages. */
export const deOrEn = (de: string, en: string) => (i18n.lang === "de" ? de : en);

/** Locale for numbers and dates. */
export function locale(): string {
  return { de: "de-DE", en: "en-GB", it: "it-IT", es: "es-ES", fr: "fr-FR", nl: "nl-NL", pl: "pl-PL", pt: "pt-BR", vi: "vi-VN" }[i18n.lang] ?? "en-GB";
}

/** Name of a language (DeepL code like "EN-US") in the UI language. */
export function languageName(code: string, de: string, en: string): string {
  if (i18n.lang === "de") return de;
  if (i18n.lang === "en") return en;
  try {
    return new Intl.DisplayNames([locale()], { type: "language" }).of(code.replace("ZH-HANS", "zh-Hans").replace("ZH-HANT", "zh-Hant")) ?? en;
  } catch {
    return en;
  }
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  const l = i18n.lang;
  let s = l === "de" ? de[key] : l === "en" ? en[key] : (CATALOG[l]?.["@" + key] ?? en[key]);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function ago(ms: number): string {
  const diff = Math.max(0, Date.now() - ms) / 60000;
  if (diff < 1) return t("justNow");
  if (diff < 60) return t("minAgo", { n: Math.floor(diff) });
  if (diff < 1440) return t("hAgo", { n: Math.floor(diff / 60) });
  return t("dAgo", { n: Math.floor(diff / 1440) });
}

export function fmtDate(ms: number): string {
  return new Date(ms).toLocaleString(locale(), { dateStyle: "medium", timeStyle: "short" });
}

export function fmtBytes(n: number): string {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / 1024 / 1024).toFixed(1)} MB`;
}
